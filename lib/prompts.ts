import type { BlockKey, Language } from "./schema";

/**
 * Все промпты проекта — только здесь.
 * Следуем «Принципам промптов» из PROJECT.MD.
 *
 * Промпт собирается из общих правил и инструкций по блокам — так один и тот же
 * текст используется и для генерации всех материалов, и для перегенерации одного блока.
 */

const LANGUAGE_NAMES: Record<Language, string> = {
  ru: "русском",
  kk: "казахском",
};

const BLOCK_INSTRUCTIONS: Record<BlockKey, (lang: string) => string> = {
  summary: () =>
    `summary — конспект по разделам в порядке занятия. В каждом разделе 2–6 тезисов: суть, а не пересказ реплик. Короткие примеры кода из занятия можно включать в тезисы.`,
  quiz: () => `quiz — 5–10 вопросов (меньше, если занятие короткое и материала не хватает). Правила:
   - вопросы проверяют ПОНИМАНИЕ (что произойдёт, почему, как применить, в чём разница), а не запоминание формулировок ментора;
   - ровно 4 варианта ответа, один правильный; correctIndex — индекс правильного (0–3);
   - неправильные варианты правдоподобные, типичные ошибки студентов;
   - позицию правильного ответа меняй от вопроса к вопросу;
   - explanation объясняет, почему ответ верный, опираясь на то, что говорилось на занятии.`,
  homework: () =>
    `homework — одно практическое задание по теме занятия, выполнимое за 1–2 часа. requirements — что конкретно сделать; criteria — проверяемые критерии оценки. Задание должно использовать только то, что проходили на занятии.`,
  faq: () =>
    `faq — ТОЛЬКО реальные вопросы студентов из транскрипта и ответы ментора на них (вопрос можно переформулировать понятнее, смысл не меняй). Если студенты вопросов не задавали — верни пустой список. Не придумывай вопросы сам.`,
  glossary: (lang) =>
    `glossary — ключевые термины занятия. Для каждого: term (как звучал на занятии), kk, ru, en (перевод или устоявшееся название; если термин не переводят — оставь его как есть), definition (1–2 предложения на ${lang} языке, в духе объяснения ментора).`,
};

const BLOCK_ORDER: BlockKey[] = ["summary", "quiz", "homework", "faq", "glossary"];

const TIMESTAMPS_PRESENT = `Строки транскрипта начинаются с таймкода в квадратных скобках: "[мм:сс]" или "[чч:мм:сс]". Таймкоды связывают материалы с записью занятия, поэтому они обязательны:
- у КАЖДОГО раздела summary — таймкод строки, с которой начинается объяснение этого раздела;
- у КАЖДОГО вопроса quiz — таймкод строки, где ментор объяснял то, что проверяет вопрос (чтобы студент мог пересмотреть этот момент);
- у КАЖДОГО пункта faq — таймкод строки, где студент задал вопрос.
Используй ТОЛЬКО таймкоды, которые реально стоят в начале строк транскрипта, и копируй их в том же формате, без скобок (например "04:27"). Не вычисляй, не округляй и не придумывай таймкоды.`;

const TIMESTAMPS_ABSENT = `В этом транскрипте нет меток времени. Во всех полях timestamp ставь null. Не придумывай таймкоды.`;

function buildPrompt(language: Language, hasTimestamps: boolean, task: string): string {
  const lang = LANGUAGE_NAMES[language];

  return `Ты — помощник ментора IT-школы Tech Orda (Казахстан). По транскрипту занятия ты готовишь черновик учебных материалов, который ментор потом проверит и отредактирует.

## Главное правило
Опирайся ТОЛЬКО на содержание транскрипта. Ничего не выдумывай: не добавляй темы, примеры, факты и вопросы, которых не было на занятии. Если чего-то в транскрипте нет — не добавляй это.

## Язык
- Все материалы пиши на ${lang} языке.
- IT-термины, названия технологий, ключевые слова и код оставляй как есть (например: "const", "callback", "event loop", "Promise").
- Речь в транскрипте смешанная (русский, казахский, английские термины), с оговорками, паузами и повторами — это нормально. Понимай смысл, а не дословные формулировки, и пиши чистым грамотным языком.

${task.replaceAll("{lang}", lang)}

## Таймкоды
${hasTimestamps ? TIMESTAMPS_PRESENT : TIMESTAMPS_ABSENT}

## Участники и персональные данные
В транскрипте участники могут быть обозначены как «Ментор» и «Студент 1», «Студент 2» и т.д. — это псевдонимы. Не упоминай в материалах имена и номера студентов и другие личные данные — пиши «студент», «один из студентов».`;
}

/**
 * Промпт для генерации всех материалов.
 * @param hasTimestamps — есть ли в транскрипте метки "[мм:сс]"
 *   (транскрипт из .vtt или вставленный текст с таймкодами).
 */
export function buildMaterialsSystemPrompt(language: Language, hasTimestamps: boolean): string {
  const lang = LANGUAGE_NAMES[language];
  const items = BLOCK_ORDER.map((key, i) => `${i + 2}. ${BLOCK_INSTRUCTIONS[key](lang)}`);
  const task = `## Что подготовить
1. title — короткая тема занятия.
${items.join("\n")}`;
  return buildPrompt(language, hasTimestamps, task);
}

/** Промпт для перегенерации одного блока: остальные материалы ментор уже отредактировал. */
export function buildBlockSystemPrompt(
  block: BlockKey,
  language: Language,
  hasTimestamps: boolean,
): string {
  const lang = LANGUAGE_NAMES[language];
  const task = `## Что подготовить
Ментор попросил заново подготовить ТОЛЬКО один блок материалов — остальные блоки он уже отредактировал. Подготовь новый вариант блока:
${BLOCK_INSTRUCTIONS[block](lang)}`;
  return buildPrompt(language, hasTimestamps, task);
}

export function buildMaterialsUserPrompt(transcript: string): string {
  return `Транскрипт занятия:

<transcript>
${transcript}
</transcript>`;
}
